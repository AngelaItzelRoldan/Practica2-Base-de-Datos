CREATE TABLE categoria (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(80) NOT NULL,
  descripcion VARCHAR(255),
  estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
  CONSTRAINT uq_categoria_nombre UNIQUE (nombre),
  CONSTRAINT ck_categoria_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE fabricante (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  correo VARCHAR(100),
  sitioweb VARCHAR(150),
  telefono VARCHAR(25),
  pais VARCHAR(60),
  estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
  codigopostal VARCHAR(15),
  CONSTRAINT uq_fabricante_correo UNIQUE (correo),
  CONSTRAINT ck_fabricante_estado CHECK (estado IN ('ACTIVO','INACTIVO'))
);

CREATE TABLE producto (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(120) NOT NULL,
  presentacion VARCHAR(80) NOT NULL,
  contenido VARCHAR(60),
  precioventa NUMERIC(10,2) NOT NULL,
  estado VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
  categoria_id INT NOT NULL,
  fabricante_id INT NOT NULL,
  CONSTRAINT ck_producto_precio CHECK (precioventa >= 0),
  CONSTRAINT ck_producto_estado CHECK (estado IN ('ACTIVO','INACTIVO')),
  CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id)
    REFERENCES categoria (id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_producto_fabricante FOREIGN KEY (fabricante_id)
    REFERENCES fabricante (id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE medicamento (
  producto_id INT PRIMARY KEY,
  principioactivo VARCHAR(120) NOT NULL,
  concentracion VARCHAR(40),
  requierereceta BOOLEAN NOT NULL DEFAULT FALSE,
  CONSTRAINT fk_medicamento_producto FOREIGN KEY (producto_id)
    REFERENCES producto (id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE otro_producto (
  producto_id INT PRIMARY KEY,
  tipoproducto VARCHAR(60) NOT NULL,
  unidadventa VARCHAR(30) NOT NULL,
  CONSTRAINT fk_otro_producto_producto FOREIGN KEY (producto_id)
    REFERENCES producto (id) ON DELETE CASCADE ON UPDATE CASCADE
);

CREATE TABLE compra (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha DATE NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL,
  descuento NUMERIC(12,2) NOT NULL DEFAULT 0,
  impuesto NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL,
  estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
  CONSTRAINT ck_compra_montos CHECK (subtotal >= 0 AND descuento >= 0 AND impuesto >= 0 AND total >= 0),
  CONSTRAINT ck_compra_estado CHECK (estado IN ('PENDIENTE','RECIBIDA','ANULADA'))
);

CREATE TABLE detalle_compra (
  compra_id INT NOT NULL,
  producto_id INT NOT NULL,
  cantidad INT NOT NULL,
  preciounitario NUMERIC(10,2) NOT NULL,
  descuento NUMERIC(10,2) NOT NULL DEFAULT 0,
  CONSTRAINT pk_detalle_compra PRIMARY KEY (compra_id, producto_id),
  CONSTRAINT ck_dcompra_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_dcompra_precio CHECK (preciounitario >= 0 AND descuento >= 0),
  CONSTRAINT fk_dcompra_compra FOREIGN KEY (compra_id)
    REFERENCES compra (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_dcompra_producto FOREIGN KEY (producto_id)
    REFERENCES producto (id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE lote (
  producto_id INT NOT NULL,
  numerolote VARCHAR(40) NOT NULL,
  compra_id INT,
  fechafabricacion DATE NOT NULL,
  fechacaducidad DATE NOT NULL,
  cantidadrecibida INT NOT NULL,
  disponibles INT NOT NULL,
  estado VARCHAR(15) NOT NULL DEFAULT 'DISPONIBLE',
  CONSTRAINT pk_lote PRIMARY KEY (producto_id, numerolote),
  CONSTRAINT ck_lote_fechas CHECK (fechacaducidad > fechafabricacion),
  CONSTRAINT ck_lote_cantidades CHECK (cantidadrecibida > 0 AND disponibles >= 0 AND disponibles <= cantidadrecibida),
  CONSTRAINT ck_lote_estado CHECK (estado IN ('DISPONIBLE','AGOTADO','VENCIDO','RETIRADO')),
  CONSTRAINT fk_lote_producto FOREIGN KEY (producto_id)
    REFERENCES producto (id) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT fk_lote_dcompra FOREIGN KEY (compra_id, producto_id)
    REFERENCES detalle_compra (compra_id, producto_id) ON DELETE RESTRICT ON UPDATE CASCADE
);

CREATE TABLE venta (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fechahora TIMESTAMP NOT NULL,
  subtotal NUMERIC(12,2) NOT NULL,
  descuento NUMERIC(12,2) NOT NULL DEFAULT 0,
  impuesto NUMERIC(12,2) NOT NULL DEFAULT 0,
  total NUMERIC(12,2) NOT NULL,
  metodopago VARCHAR(15) NOT NULL,
  estado VARCHAR(15) NOT NULL DEFAULT 'COMPLETADA',
  CONSTRAINT ck_venta_montos CHECK (subtotal >= 0 AND descuento >= 0 AND impuesto >= 0 AND total >= 0),
  CONSTRAINT ck_venta_pago CHECK (metodopago IN ('EFECTIVO','TARJETA','TRANSFERENCIA')),
  CONSTRAINT ck_venta_estado CHECK (estado IN ('COMPLETADA','ANULADA'))
);

CREATE TABLE detalle_venta (
  venta_id INT NOT NULL,
  producto_id INT NOT NULL,
  cantidad INT NOT NULL,
  preciounitario NUMERIC(10,2) NOT NULL,
  descuento NUMERIC(10,2) NOT NULL DEFAULT 0,
  CONSTRAINT pk_detalle_venta PRIMARY KEY (venta_id, producto_id),
  CONSTRAINT ck_dventa_cantidad CHECK (cantidad > 0),
  CONSTRAINT ck_dventa_precio CHECK (preciounitario >= 0 AND descuento >= 0),
  CONSTRAINT fk_dventa_venta FOREIGN KEY (venta_id)
    REFERENCES venta (id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT fk_dventa_producto FOREIGN KEY (producto_id)
    REFERENCES producto (id) ON DELETE RESTRICT ON UPDATE CASCADE
);

